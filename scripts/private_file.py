"""Write a file that holds tokens so that only its owner can read it."""

from __future__ import annotations

import os
from pathlib import Path


def write_private(path: str | Path, text: str) -> None:
    """Write text to path with mode 0600, whatever the umask or its old mode."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fptr:
        # The mode given to open only applies to a file it creates
        if hasattr(os, "fchmod"):
            os.fchmod(fd, 0o600)
        fptr.write(text)
